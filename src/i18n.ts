const DICT: Record<Lang, Record<TKey, string>> = { es, en };

export type TFn = (key: TKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = DICT[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT(): TFn {
  const lang = useStore((s) => s.ui.lang);
  return useCallback<TFn>((key, vars) => translate(lang, key, vars), [lang]);
}

