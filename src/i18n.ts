export function translateName(name: string, lang: Lang) {
  if (lang === 'es') return name;
  const rule = NAME_RULES.find(([re]) => re.test(name));
  if (!rule) return name;
  return (
    name
      .replace(rule[0], rule[1])
      .replace('(taquillas)', '(lockers)')
      // Oeste → West en los sufijos de orientación (O, SO, NO)
      .replace(/\bSO\b/g, 'SW')
      .replace(/\bNO\b/g, 'NW')
      .replace(/\bO\b/g, 'W')
  );
}

