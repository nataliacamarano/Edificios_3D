/** Algo con nombre: una estancia o una planta (con su nombre en inglés opcional). */
export type Named = string | { name: string; nameEn?: string };

/** Nombre a mostrar: en inglés, el que se haya escrito a mano o, si no, el traducido. */
export function displayName(item: Named, lang: Lang) {
  if (typeof item === 'string') return translateName(item, lang);
  return lang === 'en' && item.nameEn?.trim() ? item.nameEn : translateName(item.name, lang);
}

/** Traductor de nombres de estancias y plantas según el idioma actual. */
export function useName() {
  const lang = useStore((s) => s.ui.lang);
  return useCallback((item: Named) => displayName(item, lang), [lang]);
}
